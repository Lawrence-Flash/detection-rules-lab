"""Optional Sigma conversion through pySigma.

``validate``, ``test``, and ``coverage`` do not import pySigma. This command
does, and it exits with a clear message when those packages are absent.
Converted queries keep the field names written in the rules. No Splunk CIM or
Elastic Common Schema pipeline is applied.
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

from rulelab.paths import display_path
from rulelab.validate import validate_rules

_MISSING = """\
convert needs optional packages that are not installed:
  sigma-cli, pysigma-backend-splunk, pysigma-backend-elasticsearch

Install them with:
  python3 -m pip install -r requirements-dev.txt

validate, test, and coverage do not need those packages.
"""


def convert_rules(rules_dir: Path, output: Path) -> int:
    try:
        from sigma.backends.elasticsearch import LuceneBackend
        from sigma.backends.splunk import SplunkBackend
        from sigma.rule import SigmaRule
    except ImportError:
        print(_MISSING, file=sys.stderr)
        return 2

    _loaded, errors = validate_rules(rules_dir)
    if errors:
        for error in errors:
            print(f"ERROR {error}")
        return 1

    splunk_dir = output / "splunk"
    lucene_dir = output / "lucene"
    splunk_dir.mkdir(parents=True, exist_ok=True)
    lucene_dir.mkdir(parents=True, exist_ok=True)
    _clear_generated(splunk_dir, ".spl")
    _clear_generated(lucene_dir, ".txt")

    splunk = SplunkBackend()
    lucene = LuceneBackend()
    files = sorted(
        path
        for path in rules_dir.rglob("*")
        if path.is_file() and path.suffix in {".yml", ".yaml"}
    )
    for path in files:
        text = path.read_text(encoding="utf-8")
        try:
            rule = SigmaRule.from_yaml(text)
            splunk_queries = _as_strings(splunk.convert_rule(rule))
            lucene_queries = _as_strings(lucene.convert_rule(rule))
        except Exception as exc:  # pySigma raises several exception types
            print(f"ERROR {display_path(path)}: conversion failed: {exc}", file=sys.stderr)
            return 1
        stem = _stem(path, rules_dir)
        _write_query(splunk_dir / f"{stem}.spl", path, rule, splunk_queries, "Splunk SPL")
        _write_query(lucene_dir / f"{stem}.txt", path, rule, lucene_queries, "Elasticsearch Lucene")

    readme = output / "README.md"
    readme.write_text(_examples_readme(len(files)), encoding="utf-8")
    print(f"Wrote Splunk and Lucene examples for {len(files)} rules to {display_path(output)}")
    return 0


def _as_strings(queries: Any) -> list[str]:
    if queries is None:
        return []
    if isinstance(queries, str):
        return [queries]
    return [str(item) for item in queries]


def _stem(path: Path, rules_dir: Path) -> str:
    relative = path.relative_to(rules_dir).with_suffix("")
    return relative.as_posix().replace("/", "__")


def _write_query(path: Path, source: Path, rule: Any, queries: list[str], kind: str) -> None:
    header = [
        f"# {rule.title}",
        f"# id: {rule.id}",
        f"# source: {display_path(source)}",
        f"# format: {kind}",
        "# Field names are the Sigma field names. No product pipeline was applied.",
        "# Generated by python3 -m rulelab convert. Do not edit by hand.",
        "",
    ]
    body = "\n\n".join(queries).rstrip() + "\n"
    path.write_text("\n".join(header) + body, encoding="utf-8")


def _clear_generated(directory: Path, suffix: str) -> None:
    for path in directory.glob(f"*{suffix}"):
        path.unlink()


def _examples_readme(count: int) -> str:
    return f"""# Converted query examples

Generated by `python3 -m rulelab convert` with pySigma. These files are examples for review. Nothing here is deployed to a SIEM.

{count} rules were converted twice:

- `splunk/` is Splunk SPL from `pysigma-backend-splunk`
- `lucene/` is Elasticsearch Lucene from `pysigma-backend-elasticsearch`

Field names are copied from the Sigma rules. The command does not apply a Splunk CIM pipeline or an Elastic Common Schema pipeline, so the queries will not line up with a production sourcetype until someone maps the fields.

The lab still runs `validate`, `test`, and `coverage` with the Python standard library only. pySigma is not imported unless you run `convert`.
"""
