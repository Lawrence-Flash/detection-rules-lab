"""MITRE ATT&CK coverage for the rules in this repository."""

from __future__ import annotations

from pathlib import Path
from typing import Any

from rulelab.attack import TACTICS, TECHNIQUES, tactic_name
from rulelab.paths import display_path
from rulelab.validate import rule_techniques, validate_rules


def render_coverage(rules_dir: Path) -> tuple[str, list[str]]:
    """Return markdown and any validation errors. Markdown is empty when invalid."""
    loaded, errors = validate_rules(rules_dir)
    if errors:
        return "", errors
    return _markdown(loaded), []


def write_coverage(rules_dir: Path, output: Path) -> tuple[str, list[str]]:
    text, errors = render_coverage(rules_dir)
    if errors:
        return text, errors
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(text, encoding="utf-8")
    return text, []


def _markdown(loaded: list[tuple[Path, dict[str, Any]]]) -> str:
    by_technique: dict[str, list[Path]] = {}
    for path, rule in loaded:
        for technique_id in rule_techniques(rule["tags"]):
            by_technique.setdefault(technique_id, []).append(path)

    tactic_rules: dict[str, list[Path]] = {slug: [] for slug, _name in TACTICS}
    tactic_techniques: dict[str, set[str]] = {slug: set() for slug, _name in TACTICS}
    for technique_id, paths in by_technique.items():
        for slug in TECHNIQUES[technique_id]["tactics"]:  # type: ignore[index]
            tactic_techniques[str(slug)].add(technique_id)
            for path in paths:
                if path not in tactic_rules[str(slug)]:
                    tactic_rules[str(slug)].append(path)

    covered = [slug for slug, _name in TACTICS if tactic_rules[slug]]
    lines = [
        "# MITRE ATT&CK coverage",
        "",
        "Generated by `python3 -m rulelab coverage`. Do not edit by hand.",
        "",
        f"{len(loaded)} rules reference {len(by_technique)} techniques "
        f"across {len(covered)} of {len(TACTICS)} enterprise tactics.",
        "",
        "Tactic tags are the tactics listed on each technique's MITRE page. "
        "A rule that maps two techniques is counted under each of those tactics. "
        "Empty tactics are gaps, not an oversight to hide.",
        "",
        "## By tactic",
        "",
        "| Tactic | Techniques | Rules |",
        "| --- | ---: | ---: |",
    ]
    for slug, display in TACTICS:
        lines.append(
            f"| {display} | {len(tactic_techniques[slug])} | {len(tactic_rules[slug])} |"
        )

    lines.extend(
        [
            "",
            "## By technique",
            "",
            "| Technique | Name | Tactics | Rules |",
            "| --- | --- | --- | --- |",
        ]
    )
    for technique_id in sorted(by_technique):
        info = TECHNIQUES[technique_id]
        tactics = ", ".join(tactic_name(slug) for slug in info["tactics"])  # type: ignore[union-attr]
        rules = ", ".join(f"`{display_path(path)}`" for path in by_technique[technique_id])
        lines.append(f"| {technique_id} | {info['name']} | {tactics} | {rules} |")

    lines.extend(["", "## Rules", ""])
    lines.append("| Rule | Title | Level | Techniques |")
    lines.append("| --- | --- | --- | --- |")
    for path, rule in loaded:
        techniques = ", ".join(rule_techniques(rule["tags"]))
        lines.append(
            f"| `{display_path(path)}` | {rule['title']} | {rule['level']} | {techniques} |"
        )
    lines.append("")
    return "\n".join(lines)
